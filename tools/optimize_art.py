#!/usr/bin/env python3
"""Shrinks the delivered character art for the game and writes the list the game loads from.

  assets/units/<key>.png          (1024x1024)  -> play/assets/units/<key>.webp      (256x256)
  assets/portraits/<id>_<face>.png (1086x1448) -> play/assets/portraits/<id>_<face>.webp (height 720)

The source files are only read. An output newer than its source is skipped, so `npm run build` stays fast.
WebP is used when this Pillow supports it, PNG otherwise. src/art-manifest.ts (which files exist, with a
short content hash for cache busting) is rewritten only when it changes.

Usage: python3 tools/optimize_art.py [--force]
"""
import hashlib
import os
import sys

try:
    from PIL import Image, features
except ImportError:  # the committed outputs keep working without Pillow
    print('optimize_art: Pillow not found, skipping (committed play/assets are used as-is)')
    sys.exit(0)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_UNITS = os.path.join(ROOT, 'assets', 'units')
SRC_PORTRAITS = os.path.join(ROOT, 'assets', 'portraits')
OUT_UNITS = os.path.join(ROOT, 'play', 'assets', 'units')
OUT_PORTRAITS = os.path.join(ROOT, 'play', 'assets', 'portraits')
MANIFEST = os.path.join(ROOT, 'src', 'art-manifest.ts')

UNIT_SIZE = 256
PORTRAIT_H = 720
FACES = ('normal', 'smile', 'angry', 'sad', 'dere')
WEBP = features.check('webp')
EXT = '.webp' if WEBP else '.png'
FORCE = '--force' in sys.argv


def fresh(src, dst):
    return not FORCE and os.path.exists(dst) and os.path.getmtime(dst) >= os.path.getmtime(src)


def shrink(im, size):
    """Halves the picture step by step, then one last Lanczos pass (keeps thin outlines clean)."""
    im = im.convert('RGBA')
    w, h = size
    while im.width >= w * 2 and im.height >= h * 2:
        im = im.resize((im.width // 2, im.height // 2), Image.Resampling.LANCZOS)
    return im.resize(size, Image.Resampling.LANCZOS)


def save(im, dst, quality):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    tmp = dst + '.tmp'
    if WEBP:
        im.save(tmp, 'WEBP', quality=quality, method=6, alpha_quality=90)
    else:
        im = im.quantize(256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE) if quality < 90 else im
        im.save(tmp, 'PNG', optimize=True)
    os.replace(tmp, dst)


def pngs(d):
    return sorted(f for f in os.listdir(d) if f.lower().endswith('.png')) if os.path.isdir(d) else []


def short_hash(path):
    with open(path, 'rb') as f:
        return hashlib.sha1(f.read()).hexdigest()[:8]


def main():
    made = skipped = 0
    units, portraits = {}, {}
    for f in pngs(SRC_UNITS):
        key = f[:-4]
        src, dst = os.path.join(SRC_UNITS, f), os.path.join(OUT_UNITS, key + EXT)
        if fresh(src, dst):
            skipped += 1
        else:
            with Image.open(src) as im:
                save(shrink(im, (UNIT_SIZE, UNIT_SIZE)), dst, 90)
            made += 1
        units[key] = f'assets/units/{key}{EXT}?v={short_hash(dst)}'
    for f in pngs(SRC_PORTRAITS):
        name = f[:-4]
        if '_' not in name:
            continue
        pid, face = name.rsplit('_', 1)
        if face not in FACES:
            continue
        src, dst = os.path.join(SRC_PORTRAITS, f), os.path.join(OUT_PORTRAITS, name + EXT)
        if fresh(src, dst):
            skipped += 1
        else:
            with Image.open(src) as im:
                w = round(im.width * PORTRAIT_H / im.height)
                save(shrink(im, (w, PORTRAIT_H)), dst, 84)
            made += 1
        portraits.setdefault(pid, {})[face] = f'assets/portraits/{name}{EXT}?v={short_hash(dst)}'

    lines = [
        '// Generated by tools/optimize_art.py (npm run build). Do not edit by hand.',
        '// Paths are relative to play/index.html; ?v= is a content hash so hosts do not serve stale pictures.',
        '/** Map sprites by image key (cast id, boss id or enemy_<faction>_<role>). 256x256, feet near the bottom centre. */',
        'export const UNIT_ART: Record<string, string> = {',
        *[f"  {k}: '{v}'," for k, v in sorted(units.items())],
        '};',
        "export type Face = 'normal' | 'smile' | 'angry' | 'sad' | 'dere';",
        '/** Conversation portraits by character id, then expression. 3:4, background transparent. */',
        'export const PORTRAIT_ART: Record<string, Partial<Record<Face, string>>> = {',
        *[f"  {pid}: {{ " + ', '.join(f"{face}: '{p}'" for face, p in sorted(fs.items(), key=lambda x: FACES.index(x[0]))) + ' },'
          for pid, fs in sorted(portraits.items())],
        '};',
        '',
    ]
    text = '\n'.join(lines)
    old = open(MANIFEST, encoding='utf-8').read() if os.path.exists(MANIFEST) else ''
    if old != text:
        with open(MANIFEST, 'w', encoding='utf-8') as f:
            f.write(text)

    total = sum(os.path.getsize(os.path.join(d, f)) for d in (OUT_UNITS, OUT_PORTRAITS) if os.path.isdir(d) for f in os.listdir(d))
    print(f'optimize_art: {made} written, {skipped} up to date, play/assets {total / 1048576:.1f}MB ({EXT[1:]})')


if __name__ == '__main__':
    main()
