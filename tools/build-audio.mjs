// Copies the delivered music (assets/audio/bgm/<name>.mp3|ogg) into play/assets/audio/bgm/ and writes
// src/audio-manifest.ts, the list of tracks that have a file. Tracks without one play the synthesized placeholder
// (src/audio/songs.ts). Run by build.mjs; needs nothing but Node.
//
// - A copy newer than its source is skipped. Copies whose source was removed are deleted, so taking a file out of
//   assets/ brings the placeholder back on the next build.
// - The manifest is rewritten only when it changes; ?v= is a short content hash so hosts do not serve stale audio.
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';

const SRC = 'assets/audio/bgm', OUT = 'play/assets/audio/bgm', MANIFEST = 'src/audio-manifest.ts';
const NAMES = new Set(['title', 'prologue', 'camp', 'map_dawn', 'map_resolve', 'map_final', 'map_enemy', 'boss', 'crisis', 'daily', 'comedy', 'sad',
  'resolve', 'mystery', 'romance', 'family', 'orsted', 'final_boss', 'ending', 'victory', 'defeat', 'levelup', 'classchange', 'support']);
const EXT = ['.mp3', '.ogg'];

const files = existsSync(SRC) ? readdirSync(SRC).filter(f => EXT.some(e => f.toLowerCase().endsWith(e))).sort() : [];
mkdirSync(OUT, { recursive: true });
const list = {};
let copied = 0;
for (const f of files) {
  const name = f.slice(0, f.lastIndexOf('.')), ext = f.slice(f.lastIndexOf('.')).toLowerCase();
  if (!NAMES.has(name)) { console.warn(`build-audio: ${f} は曲リストにない名前です（無視します）`); continue; }
  const src = `${SRC}/${f}`, dst = `${OUT}/${name}${ext}`;
  if (!existsSync(dst) || statSync(dst).mtimeMs < statSync(src).mtimeMs || statSync(dst).size !== statSync(src).size) { copyFileSync(src, dst); copied++; }
  const hash = createHash('sha1').update(readFileSync(dst)).digest('hex').slice(0, 8);
  (list[name] ??= []).push(`assets/audio/bgm/${name}${ext}?v=${hash}`);
}
// mp3 first (plays everywhere), ogg as the alternative
for (const k of Object.keys(list)) list[k].sort((a, b) => (a.includes('.mp3') ? -1 : 1) - (b.includes('.mp3') ? -1 : 1));
let removed = 0;
for (const f of readdirSync(OUT)) {
  const name = f.slice(0, f.lastIndexOf('.'));
  if (!list[name]?.some(u => u.startsWith(`assets/audio/bgm/${f}?`))) { rmSync(`${OUT}/${f}`); removed++; }
}

const text = [
  '// Generated by tools/build-audio.mjs (npm run build). Do not edit by hand.',
  '// Delivered music files by track name (paths relative to play/index.html). Tracks not listed use the placeholder synth.',
  'export const BGM_FILES: Record<string, string[]> = {',
  ...Object.keys(list).sort().map(k => `  ${k}: [${list[k].map(u => `'${u}'`).join(', ')}],`),
  '};',
  '',
].join('\n');
const old = existsSync(MANIFEST) ? readFileSync(MANIFEST, 'utf8') : '';
if (old !== text) writeFileSync(MANIFEST, text);
console.log(`build-audio: ${Object.keys(list).length} tracks with files (${copied} copied, ${removed} removed), others use the placeholder synth`);
